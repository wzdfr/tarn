-- Tarn Maven 示例建表脚本（MySQL）
CREATE DATABASE IF NOT EXISTS tarn_demo DEFAULT CHARACTER SET utf8mb4;
USE tarn_demo;

CREATE TABLE IF NOT EXISTS demo_book (
    ID     BIGINT PRIMARY KEY AUTO_INCREMENT,
    TITLE  VARCHAR(128) NOT NULL,
    AUTHOR VARCHAR(64),
    STOCK  INT DEFAULT 0
);

